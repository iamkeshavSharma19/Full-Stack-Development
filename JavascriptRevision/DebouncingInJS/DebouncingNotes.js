//? In simple words, **debouncing** is a programming technique used to limit the number of times a function gets called (0:47-1:56).

//? Think of a search bar: instead of sending a new request to the server every single time a user types a letter, debouncing waits until the user has **stopped typing** for a short, set amount of time (e.g., 400 or 500 milliseconds) before sending the request (1:41-2:44).

// **Why is it useful?**

// *   **Saves resources:** It prevents your application from overwhelming the server with unnecessary requests (1:35-1:46).
// *   **Improves performance:** By reducing the workload, your application becomes faster and more efficient (0:06-0:11).
// *   **Enhances user experience:** It ensures that heavy operations only run when the user is actually finished with an action, making the app feel smoother (1:48-2:00).

